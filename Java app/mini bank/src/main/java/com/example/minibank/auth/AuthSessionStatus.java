package com.example.minibank.auth;

/*
 * Статусы сессии авторизации.
 *
 * PENDING — телефон и пароль проверены,
 *           ожидается подтверждение кодом.
 * ACTIVE — код подтверждён, выдан токен доступа.
 * REVOKED — сессия отозвана, доступ запрещён.
 *
 * Истечение срока не меняет статус автоматически.
 * При проверке доступа нужно учитывать и статус, и expiresAt.
 */

public enum AuthSessionStatus {
    PENDING,
    ACTIVE,
    REVOKED
}